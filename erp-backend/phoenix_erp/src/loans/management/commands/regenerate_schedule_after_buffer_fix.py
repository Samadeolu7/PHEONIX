"""
One-off correction for loans whose schedule was generated by the buggy
buffer-vs-term interaction in schedule_service._build_due_dates(): before
the fix, the buffer-shifted first due date was stepped forward only to the
loan's *unbuffered* maturity date, so a buffer worth a full frequency period
(e.g. 7 days on a weekly loan) silently dropped the last installment — a
23-week loan produced 22 installments instead of 23. The fix makes the
buffer a pure delay: installment count now comes from term ÷ frequency
alone, and the buffer shifts the whole schedule (including the effective
maturity) forward instead of shrinking the window.

This does NOT touch GL. Under interest_recognized_at_disbursement (the
default), total interest is posted once at disbursement as
disbursed_amount × flat rate%, which doesn't depend on installment count —
only how that same total is split across installments and which dates it
lands on changes here.

Scope: only loans with product.first_repayment_buffer_days > 0, zero
payment activity (total_paid=0 on every row) and no interest_recognized
row — i.e. untouched schedules where deleting and regenerating is safe.
Anything else is listed as "needs manual review" and left alone.

Usage:
    python manage.py regenerate_schedule_after_buffer_fix                       # report only
    python manage.py regenerate_schedule_after_buffer_fix --loan LN-770         # preview one loan
    python manage.py regenerate_schedule_after_buffer_fix --loan LN-770 --apply # apply
    python manage.py regenerate_schedule_after_buffer_fix --all-safe --apply    # apply to every safe loan
"""
from django.core.management.base import BaseCommand, CommandError
from django.db import transaction as db_transaction


class Command(BaseCommand):
    help = (
        "Regenerate repayment schedules that lost an installment to the "
        "buffer/term interaction bug in schedule_service.py. Dry-run unless --apply."
    )

    def add_arguments(self, parser):
        parser.add_argument('--loan', dest='loan_number', default=None,
                             help='Scope to a single loan. Without this, scans all loans.')
        parser.add_argument('--all-safe', action='store_true',
                             help='With --apply, correct every affected loan with zero payment activity.')
        parser.add_argument('--apply', action='store_true',
                             help='Actually write the correction. Without this, only reports.')

    def handle(self, *args, **options):
        from loans.models import LoanAccount
        from loans.schedule_service import RepaymentScheduleService, FREQ_CONFIG, _DEFAULT_FREQ, _maturity_date, _build_due_dates
        from common.models import FinancialAuditLog, log_financial_event

        loan_number = options['loan_number']
        apply_changes = options['apply']
        all_safe = options['all_safe']

        if apply_changes and not loan_number and not all_safe:
            raise CommandError("--apply requires either --loan <loan_number> or --all-safe.")

        qs = LoanAccount.all_objects.select_related('product').filter(
            disbursement_date__isnull=False,
            product__first_repayment_buffer_days__gt=0,
        ).prefetch_related('repayment_schedule')
        if loan_number:
            qs = qs.filter(loan_number=loan_number)

        safe, unsafe, unaffected = [], [], 0

        for loan in qs:
            schedule = sorted(loan.repayment_schedule.all(), key=lambda s: s.installment_number)
            if not schedule:
                continue

            buffer_days = loan.product.first_repayment_buffer_days
            date_increment, _ = FREQ_CONFIG.get(loan.repayment_frequency, _DEFAULT_FREQ)
            maturity = _maturity_date(loan.disbursement_date, loan.term_months, loan.term_unit or 'months')
            correct_due_dates = _build_due_dates(loan.disbursement_date, date_increment, maturity, buffer_days)

            if len(correct_due_dates) <= len(schedule):
                unaffected += 1
                continue

            has_activity = any(row.total_paid > 0 or row.interest_recognized for row in schedule)
            entry = (loan, schedule, correct_due_dates)
            (unsafe if has_activity else safe).append(entry)

        if loan_number and not safe and not unsafe:
            self.stdout.write(self.style.SUCCESS(
                f"{loan_number}: not affected (installment count already matches current logic) — nothing to do."
            ))
            return

        self.stdout.write(
            f"Scanned. Affected: {len(safe) + len(unsafe)}  "
            f"(safe to auto-correct: {len(safe)}, needs manual review: {len(unsafe)})  "
            f"Unaffected/skipped: {unaffected}"
        )

        for loan, schedule, correct_due_dates in unsafe:
            self.stdout.write(self.style.WARNING(
                f"  [MANUAL REVIEW] {loan.loan_number}: has {len(schedule)} installment(s) stored, "
                f"should have {len(correct_due_dates)} — has payment/GL activity, skipped."
            ))

        for loan, schedule, correct_due_dates in safe:
            self.stdout.write(
                f"  [SAFE] {loan.loan_number}: {len(schedule)} -> {len(correct_due_dates)} installment(s), "
                f"no payments recorded yet."
            )

        if not apply_changes:
            self.stdout.write(self.style.WARNING(
                "\nDRY RUN — nothing written. Re-run with --apply (and --loan or --all-safe) to write this correction."
            ))
            return

        if all_safe:
            targets = safe
        elif loan_number:
            safe_match = [e for e in safe if e[0].loan_number == loan_number]
            unsafe_match = [e for e in unsafe if e[0].loan_number == loan_number]
            if safe_match:
                targets = safe_match
            elif unsafe_match:
                raise CommandError(
                    f"{loan_number} has payment/GL activity recorded against it — this command refuses "
                    f"to delete and regenerate a schedule with real activity. Needs manual correction."
                )
            else:
                raise CommandError(f"{loan_number} is not affected by this bug.")
        else:
            targets = []

        corrected = []
        with db_transaction.atomic():
            for loan, schedule, correct_due_dates in targets:
                old_count = len(schedule)
                old_first_payment_date = loan.first_payment_date
                old_maturity_date = loan.maturity_date
                old_installment_amount = loan.installment_amount

                # LoanRepaymentSchedule uses SoftDeleteQuerySet — plain .delete()
                # only sets is_deleted=True and leaves the row in place, which
                # collides with generate()'s fresh installment_number=1 insert
                # under the (loan_id, installment_number) unique constraint.
                # These rows have zero payment activity (guaranteed by the safe
                # bucket above), so a real hard delete is correct here.
                loan.repayment_schedule.all().hard_delete()
                RepaymentScheduleService.generate(loan)

                loan.refresh_from_db()
                first_row = loan.repayment_schedule.order_by('installment_number').first()
                last_row = loan.repayment_schedule.order_by('installment_number').last()
                loan.first_payment_date = first_row.due_date
                loan.maturity_date = last_row.due_date
                loan.save(update_fields=['first_payment_date', 'maturity_date', 'updated_at'])

                log_financial_event(
                    FinancialAuditLog.LOAN_BALANCE_CORRECTION,
                    acted_by=None,
                    record_type='LoanAccount',
                    record_id=str(loan.pk),
                    description=(
                        f'Buffer/term schedule regeneration — {loan.loan_number}: rebuilt schedule from '
                        f'{old_count} to {len(correct_due_dates)} installment(s) to match the fixed '
                        f'buffer-as-delay-not-shrink logic in schedule_service.py.'
                    ),
                    extra={
                        'loan_number': loan.loan_number,
                        'product_id': loan.product_id,
                        'buffer_days': loan.product.first_repayment_buffer_days,
                        'installments_before': old_count,
                        'installments_after': len(correct_due_dates),
                        'installment_amount_before': str(old_installment_amount),
                        'installment_amount_after': str(loan.installment_amount),
                        'first_payment_date_before': str(old_first_payment_date),
                        'first_payment_date_after': str(loan.first_payment_date),
                        'maturity_date_before': str(old_maturity_date),
                        'maturity_date_after': str(loan.maturity_date),
                        'source_command': 'regenerate_schedule_after_buffer_fix',
                    },
                )
                corrected.append(loan.loan_number)

        self.stdout.write(self.style.SUCCESS(
            f"\nApplied. Corrected {len(corrected)} loan(s): {', '.join(corrected)}"
        ))
