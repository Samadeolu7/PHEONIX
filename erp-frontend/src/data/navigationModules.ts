// Helper function to get module by id
export const getModuleById = (id: string): NavigationModule | undefined => {
  return navigationModules.find(module => module.id === id);
};

// Helper function to get navigation item by path
export const getNavigationItemByPath = (
  path: string
): { module: NavigationModule; item: NavigationModule['children'][number] } | undefined => {
  for (const module of navigationModules) {
    const item = module.children.find(child => child.path === path);
    if (item) {
      return { module, item };
    }
  }
  return undefined;
};

// Helper function to filter modules by permissions
export const getModulesForUser = (userPermissions: string[]): NavigationModule[] => {
  return navigationModules
    .map(module => ({
      ...module,
      children: module.children.filter(
        item =>
          !item.permissions ||
          item.permissions.some(permission => userPermissions.includes(permission))
      ),
    }))
    .filter(
      module =>
        !module.permissions ||
        module.permissions.some(permission => userPermissions.includes(permission))
    );
};
