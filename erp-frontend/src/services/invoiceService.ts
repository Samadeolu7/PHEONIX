export const invoiceService = {
  // Invoice CRUD
  async getInvoices(filters?: InvoiceFilters) {
    return api.get('/incomes/invoices/', { params: filters });
  },

  async createInvoice(data: CreateInvoiceData): Promise<Invoice> {
    return api.post('/incomes/invoices/', data);
  },

  async getInvoice(id: number): Promise<Invoice> {
    return api.get(`/incomes/invoices/${id}/`);
  },

  async updateInvoice(id: number, data: Partial<CreateInvoiceData>): Promise<Invoice> {
    return api.put(`/incomes/invoices/${id}/`, data);
  },

  async deleteInvoice(id: number) {
    return api.delete(`/incomes/invoices/${id}/`);
  },

  // Post invoice (recognize revenue)
  async postInvoice(id: number) {
    return api.post(`/incomes/invoices/${id}/post/`);
  },

  // Payment recording
  async recordPayment(
    id: number,
    data: {
      amount: string;
      payment_date: string;
      payment_method: string;
      bank_account_id?: number;
      reference?: string;
      notes?: string;
      /** Optional per-line-item allocation. If omitted, backend distributes proportionally. */
      line_item_allocations?: LineItemAllocation[];
    }
  ) {
    return api.post(`/incomes/invoices/${id}/record_payment/`, data);
  },

  // Get payment history for an invoice (includes reversal request status)
  async getPaymentHistory(id: number) {
    return api.get(`/incomes/invoices/${id}/payment_history/`);
  },

  // List all payment reversal requests (for the Approvals page)
  async listPaymentReversalRequests(params?: {
    status?: 'pending' | 'approved' | 'rejected';
    invoice_id?: number;
  }): Promise<{
    results: Array<{
      id: number;
      invoice_id: number;
      invoice_number: string;
      client_name: string | null;
      payment_reference: string;
      amount: string;
      reason: string;
      status: 'pending' | 'approved' | 'rejected';
      requested_by: string | null;
      created_at: string;
      approved_by: string | null;
      approved_at: string | null;
      rejection_reason: string;
      draft_journal_entry_ref: string | null;
    }>;
    count: number;
  }> {
    return api.get('/incomes/payment-reversal-requests/', { params });
  },

  // Step 1: Request a payment reversal (creates draft GL entry, pending approval)
  async requestPaymentReversal(
    id: number,
    data: { payment_reference: string; reason: string }
  ): Promise<{
    success: boolean;
    message: string;
    reversal_request_id: number;
    draft_journal_entry_id: number;
    draft_journal_entry_ref: string;
    amount: string;
  }> {
    return api.post(`/incomes/invoices/${id}/request_payment_reversal/`, data);
  },

  // Step 2a: Approve a pending reversal request (approver only)
  async approvePaymentReversal(
    id: number,
    data: { reversal_request_id: number }
  ): Promise<{ success: boolean; message: string; reversed_amount: string; invoice: Invoice }> {
    return api.post(`/incomes/invoices/${id}/approve_payment_reversal/`, data);
  },

  // Step 2b: Reject a pending reversal request (approver only)
  async rejectPaymentReversal(
    id: number,
    data: { reversal_request_id: number; rejection_reason: string }
  ): Promise<{ success: boolean; message: string; reversal_request_id: number }> {
    return api.post(`/incomes/invoices/${id}/reject_payment_reversal/`, data);
  },

  // Mark invoice as sent
  async markAsSent(id: number, data: any) {
    return api.post(`/incomes/invoices/${id}/mark_sent/`, data);
  },

  // Invoice Actions (Critical Missing Endpoints)
  async sendInvoiceEmail(id: number, data: { email: string; subject?: string; message?: string }) {
    return api.post(`/incomes/invoices/${id}/send-email/`, data);
  },

  async getInvoicePdf(id: number): Promise<Blob> {
    const response = await fetch(`/api/incomes/invoices/${id}/pdf/`, {
      headers: {
        Authorization: `Bearer ${localStorage.getItem('accessToken') || sessionStorage.getItem('accessToken')}`,
      },
    });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    return response.blob();
  },

  async voidInvoice(id: number, data: { reason?: string }) {
    return api.post(`/incomes/invoices/${id}/void/`, data);
  },

  // Credit Notes (Nested under invoices)
  async getCreditNotes(
    invoiceId: number,
    filters?: {
      applied_to_account?: boolean;
      client?: number;
      issue_date?: string;
      ordering?: string;
      original_invoice?: number;
      page?: number;
      search?: string;
      status?: 'draft' | 'issued' | 'applied' | 'cancelled';
    }
  ) {
    return api.get(`/inventory/invoices/${invoiceId}/credit-notes/`, { params: filters });
  },

  async createCreditNote(invoiceId: number, data: CreateCreditNoteData): Promise<CreditNote> {
    return api.post(`/inventory/invoices/${invoiceId}/credit-notes/`, data);
  },

  async getCreditNote(invoiceId: number, creditNoteId: number): Promise<CreditNote> {
    return api.get(`/inventory/invoices/${invoiceId}/credit-notes/${creditNoteId}/`);
  },

  async updateCreditNote(
    invoiceId: number,
    creditNoteId: number,
    data: Partial<CreateCreditNoteData>
  ): Promise<CreditNote> {
    return api.put(`/inventory/invoices/${invoiceId}/credit-notes/${creditNoteId}/`, data);
  },

  async deleteCreditNote(invoiceId: number, creditNoteId: number) {
    return api.delete(`/inventory/invoices/${invoiceId}/credit-notes/${creditNoteId}/`);
  },

  // Credit Note Actions
  async issueCreditNote(
    invoiceId: number,
    creditNoteId: number,
    data: CreateCreditNoteData
  ): Promise<CreditNote> {
    return api.post(`/inventory/invoices/${invoiceId}/credit-notes/${creditNoteId}/issue/`, data);
  },

  async applyCreditNote(
    invoiceId: number,
    creditNoteId: number,
    data: { notes?: string }
  ): Promise<{ notes?: string }> {
    return api.post(`/inventory/invoices/${invoiceId}/credit-notes/${creditNoteId}/apply/`, data);
  },

  async cancelCreditNote(
    invoiceId: number,
    creditNoteId: number,
    data: { cancellation_reason: string }
  ): Promise<{ cancellation_reason: string }> {
    return api.post(`/inventory/invoices/${invoiceId}/credit-notes/${creditNoteId}/cancel/`, data);
  },

  async reverseCreditNote(
    invoiceId: number,
    creditNoteId: number,
    data: { reversal_reason: string }
  ): Promise<{ reversal_reason: string }> {
    return api.post(`/inventory/invoices/${invoiceId}/credit-notes/${creditNoteId}/reverse/`, data);
  },

  async getCreditNotePdf(invoiceId: number, creditNoteId: number): Promise<Blob> {
    const response = await fetch(
      `/api/inventory/invoices/${invoiceId}/credit-notes/${creditNoteId}/pdf/`,
      {
        headers: {
          Authorization: `Bearer ${localStorage.getItem('accessToken') || sessionStorage.getItem('accessToken')}`,
        },
      }
    );
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    return response.blob();
  },

  // Bulk Invoice Operations
  async createBulkInvoices(data: BulkInvoiceData): Promise<BulkInvoiceResult> {
    return api.post('/incomes/invoices/bulk_create/', data);
  },

  async sendBulkInvoices(
    invoiceIds: number[],
    options?: { email_template?: string }
  ): Promise<{
    success: boolean;
    sent_count: number;
    failed_count: number;
    results: { id: number; status: 'sent' | 'failed'; error?: string }[];
  }> {
    return api.post('/incomes/invoices/bulk_send/', {
      invoice_ids: invoiceIds,
      ...options,
    });
  },

  // Batch Review and Approval Methods
  async getBatchSample(
    batchId: string,
    samplePercent: number = 5
  ): Promise<{
    batch_id: string;
    total_invoices: number;
    sample_size: number;
    sample_invoices: Invoice[];
    discrepancies: {
      invoice_id: number;
      issue_type: string;
      description: string;
      severity: 'high' | 'medium' | 'low';
    }[];
  }> {
    return api.get(`/incomes/invoices/batch-sample/`, {
      params: { batch_id: batchId, sample_pct: samplePercent },
    });
  },

  async downloadBatchApprovalReport(batchId: string): Promise<Blob> {
    const response = await fetch(
      `/api/incomes/invoices/batch-approval-report/?batch_id=${batchId}`,
      {
        headers: {
          Authorization: `Bearer ${localStorage.getItem('accessToken') || sessionStorage.getItem('accessToken')}`,
        },
      }
    );
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    return response.blob();
  },
};
