// src/services/invoiceService.ts
import { api } from './api';

// Invoice Line Item - supports service, inventory, and custom items
export interface InvoiceItem {
  id?: number;
  item_type: 'service' | 'inventory' | 'custom';
  /** ServiceItem FK — required for item_type='service' */
  service_item?: number;
  service_item_details?: {
    id: number;
    name: string;
    code: string;
    creates_entitlement: boolean;
    /** e.g. 'tuition', 'boarding', 'transport', 'inventory' */
    service_type?: string;
    allows_material_requests?: boolean;
    material_request_config?: {
      allowed_categories?: string[];
      allowed_item_types?: string[];
      [key: string]: unknown;
    } | null;
  };
  inventory_item?: number;
  inventory_item_details?: {
    id: number;
    name: string;
    sku: string;
    category?: number;
    category_name?: string;
    /** Short code for the category, e.g. 'CAT-001' */
    category_code?: string;
    /** Broad type label for the category, e.g. 'Book', 'Uniform' */
    category_item_type?: string;
  };
  // Flat category / type fields (populated by InvoiceItemSerializer when item_type='inventory')
  inventory_item_category?: number | null;
  inventory_item_category_name?: string | null;
  inventory_item_category_code?: string | null;
  inventory_item_category_item_type?: string | null;
  // Flat MR fields (populated when item_type='service')
  service_item_service_type?: string | null;
  service_item_allows_material_requests?: boolean | null;
  service_item_material_request_config?: {
    allowed_categories?: string[];
    allowed_item_types?: string[];
    [key: string]: unknown;
  } | null;
  description: string;
  quantity: string;
  unit_price: string;
  line_total: string;
  // Per-item payment tracking (read-only, set by backend)
  amount_paid?: string;
  line_balance?: string;
  payment_percentage?: string;
  // Entitlement tracking
  creates_entitlement?: boolean;
  entitlement?: number | null;
  metadata?: any;
}

/** A per-line-item payment allocation sent with a payment request */
export interface LineItemAllocation {
  invoice_item_id: number;
  amount: string;
  notes?: string;
}

// Unified Invoice - supports multiple line items
export interface Invoice {
  id: number;
  client: number;
  client_name: string;
  invoice_number: string;
  invoice_date: string;
  due_date: string;
  description?: string;
  notes?: string;

  // New unified amounts
  subtotal: string;
  discount_amount: string;
  tax_amount: string;
  total_amount: string;
  amount_paid: string;
  balance: string;

  // Optional primary fee structure (for bulk generation)
  fee_structure?: number;
  fee_structure_name?: string;

  // Line items
  items: InvoiceItem[];

  status: 'draft' | 'sent' | 'partial' | 'paid' | 'overdue' | 'cancelled';
  metadata?: any;

  // Accounting
  is_posted: boolean;
  posted_at?: string;
  posted_by?: number;

  inventory_allocation?: number;
  is_overdue: boolean;
  created_at: string;
  updated_at: string;

  // Legacy fields (deprecated)
  amount?: string; // Use total_amount instead
}

